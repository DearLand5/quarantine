// Распознавание намерений в свободно введённом тексте (без языковой модели).
// Работает по корням слов и простым шаблонам; честно возвращает 'unknown', если не уверен.
// Также находит упоминания жильцов по имени, чтобы в общем чате ответил тот, к кому обратились.

const PATTERNS = [
  ['insult', /(дура|идиот|заткн|тупой|тупая|урод|пош[её]л|отвали|бред|псих|достал)/],
  ['ask_knock', /(стук|стуч|три раза|тр[её]х раз)/],
  ['ask_52', /(52|пятьдесят втор|ветров|коля|николай|пломб|опечат)/],
  ['ask_power', /(свет|электр|щит|автомат|рубильник|пробк)/],
  ['ask_history', /(истори|построен|давно жив|нии|кристалл|институт|объект|п\/я|подвал|котельн)/],
  ['ask_quarantine', /(карантин|что происходит|почему (нас )?закрыл|оцеплен|военн|газ|мчс|штаб|учени|выпуст)/],
  ['ask_where', /(где (ты|вы)|(ты|вы) дома|(ты|вы) где|у себя\?)/],
  ['ask_who', /(кто (ты|вы|это)|ты кто|вы кто)/],
  ['water', /(вод[аыу]|бутыл|еда|продукт|хлеб|запас)/],
  ['photo', /(фот|снимок|сфоткa|скрин|камер)/],
  ['need_help', /(помогите|помоги|нужна помощь|плохо|страшно|боюсь)/],
  ['offer_help', /(помогу|помочь|схожу|принесу|могу (сходить|принести|помочь)|давай(те)? я|отнесу)/],
  ['how_are_you', /(как (ты|вы|дела|соня|самочувств|настроен|там)|вы как|ты как|вс[её] (ли )?(хорошо|нормально)\?)/],
  ['thanks', /(спасиб|благодар|спс|пасиб)/],
  ['calm', /(успокой|не (волнуй|переживай|паникуй)|вс[её] будет|нормально вс[её]|всё хорошо)/],
  ['greet', /^(привет|здравствуй|здрасьте|добр(ый|ой|ого) (вечер|ночи|утр)|хай|салют|ку(?![а-яa-z0-9])|доброй ночи)/],
  ['agree', /^(да|ага|ок|окей|хорошо|ладно|конечно|согласен|сделаю|понял|принял|договорились)(?![а-яa-z0-9])/],
  ['disagree', /^(нет|не буду|не пойду|не могу|не хочу|отказ|никак)(?![а-яa-z0-9])/],
];

const NAMES = [
  ['zinaida', /(зинаид|зина(?![а-яa-z0-9])|павловн|крылова)/],
  ['marina', /(марин|ковал[её]в)/],
  ['denis', /(денис|ден(?![а-яa-z0-9])|шаров)/],
  ['gennady', /(геннад|гена(?![а-яa-z0-9])|борисыч|борисович|лапин)/],
  ['olga', /(ольг|оля(?![а-яa-z0-9])|ремез)/],
  ['lisa', /(лиз[аеу])/],
  ['artur', /(артур)/],
  ['vetrov', /(ветров)/],
];

export function normalize(text) {
  return String(text).toLowerCase().replace(/ё/g, 'е').replace(/[«»"“”!,.;:()]+/g, ' ').replace(/\s+/g, ' ').trim();
}

export function recognize(text) {
  const n = normalize(text);
  const nq = n.replace(/\?/g, ' ?');
  const intents = [];
  for (const [intent, re] of PATTERNS) if (re.test(nq) || re.test(n)) intents.push(intent);
  const mentions = NAMES.filter(([, re]) => re.test(n)).map(([id]) => id);
  const isQuestion = /\?/.test(text) || /^(кто|что|где|когда|почему|зачем|как|а вы|а ты)/.test(n);
  return { intents: intents.length ? intents : ['unknown'], primary: intents[0] || 'unknown', mentions, isQuestion, text: n };
}

/** Подходит ли распознанный текст к варианту ответа в выборе (по списку намерений). */
export function matchOption(result, options) {
  let best = null;
  let bestScore = 0;
  for (const opt of options) {
    let score = 0;
    for (const intent of opt.intents || []) {
      const idx = result.intents.indexOf(intent);
      if (idx >= 0) score += 3 - Math.min(2, idx);
    }
    if (score > bestScore) { best = opt; bestScore = score; }
  }
  return bestScore > 0 ? best : null;
}
